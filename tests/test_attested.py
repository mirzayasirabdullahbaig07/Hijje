import json
from pathlib import Path

import pytest

from hijje.attested import (
    analyze,
    diff_patterns,
    expand_paths,
    load_attested,
    lookup,
    rule_check,
    summary,
    to_markdown,
    variation_patterns,
)
from hijje.cli import main

FIXTURES = Path(__file__).resolve().parent / "fixtures"
LEXICON = str(FIXTURES / "lexicon_sample.tsv")    # native, spelling, count
ALIGNED = str(FIXTURES / "aligned_sample.tsv")    # native, spelling (no count), with junk lines


def test_lexicon_file_is_read_with_its_counts():
    table, stats = load_attested([LEXICON])
    assert table["پانی"] == {"pani": 3, "paani": 2, "panee": 1}
    assert table["سوال"] == {"sawal": 3, "saval": 1}
    assert stats == {"pairs read": 8}


def test_aligned_file_is_cleaned_and_every_dropped_line_is_counted():
    table, stats = load_attested([ALIGNED])
    assert table == {"گھر": {"ghar": 2}, "پانی": {"pani": 1}}   # "Ghar." is lowercased and stripped
    assert stats == {
        "pairs read": 3,
        "skipped: malformed line": 1,
        "skipped: more than one word on the line": 1,
        "skipped: source word is not in native script": 1,
        "skipped: spelling has digits or symbols": 1,
    }


def test_several_files_are_merged_and_wildcards_are_expanded():
    table, _ = load_attested([str(FIXTURES / "*_sample.tsv")])
    assert table["پانی"]["pani"] == 4
    assert expand_paths([str(FIXTURES / "*_sample.tsv")]) == [ALIGNED, LEXICON]
    assert expand_paths(["no_such_file.tsv"]) == ["no_such_file.tsv"]


@pytest.mark.parametrize(
    "a, b, expected",
    [
        ("pani", "paani", ["a ~ aa"]),
        ("theek", "thik", ["i ~ ee"]),
        ("sawal", "saval", ["v ~ w"]),
        ("karna", "krna", ["a ~ (nothing)"]),
        ("mujhe", "muje", ["h ~ (nothing)"]),
        ("achha", "acha", ["h ~ hh"]),
        ("pani", "pany", ["i ~ y [word end]"]),
        ("pani", "panee", ["i ~ ee [word end]"]),
        ("hai", "hy", ["y ~ ai [word end]"]),
        ("jagah", "jaga", ["h ~ (nothing) [word end]"]),
        ("paani", "panee", ["a ~ aa", "i ~ ee [word end]"]),
        ("kitab", "kitab", []),
    ],
)
def test_diff_patterns(a, b, expected):
    assert diff_patterns(a, b) == expected
    assert diff_patterns(b, a) == expected   # the label does not depend on the order


def test_summary_and_patterns():
    table, _ = load_attested([LEXICON])
    assert summary(table) == {
        "native_words": 4,
        "words_with_several_spellings": 3,
        "distinct_spellings": 8,
        "spellings_per_word": 2.0,
    }
    patterns = {p["pattern"]: p for p in variation_patterns(table)}
    assert {k: v["words"] for k, v in patterns.items()} == {
        "a ~ aa": 1, "i ~ ee": 1, "i ~ ee [word end]": 1, "v ~ w": 1,
    }
    # the example is a pair that differs in this one way only, when such a pair exists
    assert patterns["a ~ aa"]["example"] == ["paani", "pani"]


def test_rule_check_counts_what_people_also_wrote():
    table, _ = load_attested([LEXICON])
    result = rule_check(table)
    rules = result["per_rule"]
    # "paani" -> "pani" is generated by long_a and a person wrote "pani"
    assert (rules["long_a"]["generated"], rules["long_a"]["attested"]) == (1, 1)
    assert rules["long_a"]["attested_example"] == ["paani", "pani"]
    # long_i: pani->panee (seen), theek->thik (seen), panee->pani (seen), paani->paanee (not seen)
    assert (rules["long_i"]["generated"], rules["long_i"]["attested"]) == (4, 3)
    assert rules["long_i"]["share"] == pytest.approx(0.75)
    assert rules["long_i"]["unattested_example"] == ["paani", "paanee"]
    # rules that generated nothing have no share
    assert rules["q_k"]["generated"] == 0 and rules["q_k"]["share"] is None
    # pairs: 3 for pani, 1 for theek, 1 for sawal; sawal/saval is not one rule edit
    assert (result["attested_pairs"], result["pairs_explained_by_one_edit"]) == (5, 3)
    assert result["coverage"] == pytest.approx(0.6)


def test_a_pair_is_explained_whichever_spelling_the_rule_starts_from():
    # final_h turns "jagah" into "jaga"; no rule adds an "h" to "jaga".
    result = rule_check({"جگہ": {"jaga": 1, "jagah": 1}})
    assert (result["attested_pairs"], result["pairs_explained_by_one_edit"]) == (1, 1)
    assert result["per_rule"]["final_h"]["attested_example"] == ["jagah", "jaga"]


def test_words_with_one_spelling_do_not_count_against_a_rule():
    table = {"کتاب": {"kitaab": 1}}
    result = rule_check(table)
    assert all(e["generated"] == 0 for e in result["per_rule"].values())
    assert result["attested_pairs"] == 0 and result["coverage"] is None


def test_lookup_lists_every_spelling_most_frequent_first():
    table, _ = load_attested([LEXICON])
    found = lookup(table, ["Pani", "zzz"])
    assert found["pani"] == [{"native": "پانی", "spellings": [("pani", 3), ("paani", 2), ("panee", 1)]}]
    assert found["zzz"] == []


def test_report_and_cli(tmp_path, capsys):
    result = analyze([LEXICON], show=["sawal"])
    text = to_markdown(result)
    assert "| `v ~ w` | 1 | saval / sawal |" in text
    assert "| `long_a` | baat → bat | 1 | 1 | 100.0% | – |" in text
    assert "- **sawal** = سوال: sawal (3), saval (1)" in text
    json.dumps(result, ensure_ascii=False)

    out = tmp_path / "attested"
    assert main(["attested", "--pairs", LEXICON, ALIGNED, "--out", str(out), "--show", "pani"]) == 0
    assert "pani (4), paani (2), panee (1)" in capsys.readouterr().out
    saved = json.loads((out / "attested.json").read_text(encoding="utf-8"))
    assert saved["summary"]["native_words"] == 5
    assert (out / "attested.md").read_text(encoding="utf-8").startswith("# Rules checked against")


def test_cli_reports_missing_or_unusable_files(tmp_path, capsys):
    assert main(["attested", "--pairs", str(tmp_path / "nope.tsv")]) == 1
    assert "file not found" in capsys.readouterr().err
    empty = tmp_path / "empty.tsv"
    empty.write_text("only one column\n", encoding="utf-8")
    assert main(["attested", "--pairs", str(empty)]) == 1
    assert "no usable" in capsys.readouterr().err
